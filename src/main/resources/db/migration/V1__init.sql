create table teacher_user (
    id              bigint generated by default as identity primary key,
    username        varchar(64)  not null unique,
    password_hash   varchar(100) not null,
    display_name    varchar(120) not null,
    role            varchar(16)  not null,
    enabled         boolean      not null default true,
    created_at      timestamp with time zone not null
);

create table course (
    id          bigint generated by default as identity primary key,
    owner_id    bigint       not null references teacher_user(id),
    code        varchar(32)  not null,
    name        varchar(200) not null,
    created_at  timestamp with time zone not null,
    constraint uq_course_owner_code unique (owner_id, code)
);

create table roster_entry (
    id          bigint generated by default as identity primary key,
    course_id   bigint       not null references course(id) on delete cascade,
    student_no  varchar(32)  not null,
    full_name   varchar(200) not null,
    constraint uq_roster unique (course_id, student_no)
);

create table classroom (
    id             bigint generated by default as identity primary key,
    owner_id       bigint        not null references teacher_user(id),
    name           varchar(120)  not null,
    latitude       double precision,
    longitude      double precision,
    radius_m       integer,
    ble_beacon_id  varchar(16),
    ble_key_hex    varchar(64),
    created_at     timestamp with time zone not null
);

create table class_session (
    id                            bigint generated by default as identity primary key,
    course_id                     bigint       not null references course(id),
    classroom_id                  bigint       references classroom(id),
    title                         varchar(200) not null,
    code                          varchar(6)   not null,
    status                        varchar(16)  not null,
    duration_minutes              integer      not null,
    refresh_ms                    integer      not null,
    required_scans                integer      not null,
    max_span_slots                integer      not null,
    max_token_age_ms              integer      not null,
    latency_margin_ms             integer      not null,
    default_latency_threshold_ms  integer      not null,
    screen_area_ratio_threshold   double precision not null,
    require_roster                boolean      not null,
    geo_mode                      varchar(16)  not null,
    ble_mode                      varchar(16)  not null,
    frame_capture                 boolean      not null,
    epoch_start_ms                bigint,
    opened_at                     timestamp with time zone,
    closes_at                     timestamp with time zone,
    closed_at                     timestamp with time zone,
    baseline_latency_ms           integer,
    baseline_area_ratio_max       double precision,
    created_at                    timestamp with time zone not null
);
create index ix_session_code_status on class_session(code, status);

create table calibration_run (
    id               bigint generated by default as identity primary key,
    session_id       bigint       not null references class_session(id) on delete cascade,
    label            varchar(32)  not null,
    min_latency_ms   integer      not null,
    max_area_ratio   double precision not null,
    valid_scan_count integer      not null,
    clock_rtt_ms     integer      not null,
    created_at       timestamp with time zone not null
);

create table checkin_attempt (
    id                    uuid primary key,
    session_id            bigint       not null references class_session(id) on delete cascade,
    student_no            varchar(32)  not null,
    device_id             varchar(32)  not null,
    ip                    varchar(64),
    user_agent            varchar(512),
    state                 varchar(16)  not null,
    result_code           varchar(32),
    frame_path            varchar(255),
    frame_seq             integer,
    ble_nonce             varchar(16),
    ble_nonce_expires_ms  bigint,
    ble_verified          boolean      not null default false,
    sync1_offset_ms       integer,
    sync1_rtt_ms          integer,
    created_at            timestamp with time zone not null,
    expires_at            timestamp with time zone not null
);
create index ix_attempt_session on checkin_attempt(session_id);

create table scan_record (
    id                   bigint generated by default as identity primary key,
    attempt_id           uuid         not null references checkin_attempt(id) on delete cascade,
    raw_token            varchar(64)  not null,
    seq                  integer,
    ts_ms                bigint,
    first_seen_server_ms bigint       not null,
    arrival_ms           bigint       not null,
    frame_time_source    varchar(16)  not null,
    frame_w              integer      not null,
    frame_h              integer      not null,
    corners              varchar(400),
    area_ratio           double precision,
    valid                boolean      not null,
    reason               varchar(32),
    clock_suspect        boolean      not null default false,
    duplicate            boolean      not null default false
);
create index ix_scan_attempt on scan_record(attempt_id);

create table attendance (
    id                    bigint generated by default as identity primary key,
    session_id            bigint       not null references class_session(id) on delete cascade,
    student_no            varchar(32)  not null,
    full_name             varchar(200),
    source                varchar(16)  not null,
    attempt_id            uuid,
    device_id             varchar(32),
    status                varchar(16)  not null,
    flags                 varchar(500) not null default '',
    min_latency_ms        integer,
    latency_threshold_ms  integer,
    threshold_source      varchar(16),
    area_ratio_max        double precision,
    area_threshold        double precision,
    geo_state             varchar(16)  not null default 'OFF',
    geo_lat               double precision,
    geo_lng               double precision,
    geo_accuracy_m        double precision,
    geo_distance_m        double precision,
    clock_offset_ms       integer,
    clock_rtt_ms          integer,
    camera_id_hash        varchar(64),
    camera_label          varchar(200),
    user_agent            varchar(512),
    ble_verified          boolean      not null default false,
    frame_path            varchar(255),
    teacher_decision      varchar(16)  not null default 'NONE',
    teacher_note          varchar(500),
    decided_at            timestamp with time zone,
    created_at            timestamp with time zone not null,
    constraint uq_att_student unique (session_id, student_no),
    constraint uq_att_device  unique (session_id, device_id)
);
create index ix_att_session on attendance(session_id);
